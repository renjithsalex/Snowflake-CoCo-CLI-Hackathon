-- =============================================================================
-- 05_DYNAMIC_TABLES: All 8 dynamic tables in dependency order
-- =============================================================================
-- DEPENDENCY CHAIN:
--   RAW.SENSOR_READINGS → DT_SENSOR_CLEAN → DT_SENSOR_FEATURES_15M → DT_ASSET_HEALTH
--   RAW.PRODUCTION_ORDERS → DT_OEE_SHIFT → DT_OEE_LINE_DAILY → DT_OEE_PLANT_DAILY
